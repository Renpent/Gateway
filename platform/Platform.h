// OS ごとの初期化。ソケット以外で OS を知る必要が出た2つをここにまとめてある。
//
// どちらも「無くても動くが、無いと質が落ちる」たぐいのもので、Windows でだけ効く。

#pragma once

namespace platform {

/// main の先頭で一度だけ呼ぶ。
///
/// Windows でやること：
///   1. コンソールを UTF-8 に切り替える。ソースも文字列リテラルも UTF-8 に統一している
///      （MSVC は /utf-8、gcc は既定）ので、出力側も合わせないと化ける。両 OS で実行文字
///      セットが揃うので、CP932 に無い文字をリテラルに書けるようになる
///   2. タイマ分解能を 1 ms に上げる。既定の 15.6 ms のままだと、20 Hz（50 ms 周期）の
///      ループで起床が平均 7 ms 遅れる。実測で平均 7.6 ms / 最大 14.3 ms だった
///
/// Linux では何もしない。端末は UTF-8 で、nanosleep の分解能は元から十分細かい。
void initPlatform();

/// 終了時に呼ぶ。上げたタイマ分解能を戻す。
/// 分解能はシステム全体の設定なので、上げっぱなしにすると他のプロセスの消費電力に響く。
void shutdownPlatform();

}  // namespace platform
