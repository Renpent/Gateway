// HLA のクラスがオブジェクトかインタラクションか。
//
// **ゲートウェイがこれを見るのは1箇所だけ** — 送り切れなかったぶんを次の周期へ持ち越すか、
// 捨てて撮り直すか。その扱いが正反対で、取り違えると静かに壊れるので、bool ではなく
// 名前のある型にしてある。
//
// 値は FOM の語彙そのままにしてある。以前は Snapshot / Events という「振る舞いのほうの名前」
// だったが、それだと配線を読むたびに「このクラスはオブジェクトだから Snapshot」と頭の中で
// 訳し直すことになる。訳は下の表に1度だけ書いてあればよい。

#pragma once

namespace gw {

enum class ClassKind {
    /// オブジェクトクラス。HLA ツールの getRemoteXXX() で「その瞬間の全体像」が取れるので、
    /// 毎周期それを写して送る。1周期ぶん落ちても次の周期が現在値を運ぶので**自己回復する**。
    /// 送り残しは次の周期には古い値になっているので、**捨てて撮り直す**のが正しい。
    Object,

    /// インタラクションクラス。イベントとして飛んでくるので、1件1件が意味を持つ。
    /// 落とすと二度と戻らないし、次の周期が埋め合わせてもくれない。
    /// 送り残しは**持ち越す**。
    Interaction,
};

}  // namespace gw
