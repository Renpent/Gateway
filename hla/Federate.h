// HLA 側との継ぎ目のまとめ。**この2つを RTI の API で実装すれば移植が済む。**
//
// クラス定義そのものは FromHla.h と ToHla.h にある。このファイルは両方を1行で入れるためと、
// **どちらにも等しくかかる取り決め**を1箇所に書くために置いてある。
//
// 向きが2つあることに注意。名前が示すとおりだが、HLA の publish / subscribe とは逆に見える：
//
//   FromHla<T>  HLA → UDP。RTI が反映した属性更新を T に詰めて渡す（reflectAttributeValues）
//               RTI に対しては subscribe。UDP 側の相手は gw::Publisher（送信）
//   ToHla<T>    UDP → HLA。UDP から復元した T を HLA に押し込む（updateAttributeValues）
//               RTI に対しては publish。UDP 側の相手は gw::Subscriber（受信）
//
// 実装側で必要になるが、インタフェースに現れないもの：
//   - オブジェクトインスタンスハンドルと T の対応表（HLA はインスタンス単位、ICD はレコード単位）
//   - 属性ハンドルとメンバの対応（生成コードはメンバ順を保証するが、ハンドルは実行時に取る）
//   - 部分更新の扱い。ICD は常に全属性ぶんの箱を送るので、
//     未受信の属性を「前回値」で埋めるか既定値で埋めるかを決める必要がある
//
// ─── スレッドの取り決め ───────────────────────────────────────────────
//
// **drain() と accept() は周期ループのスレッドから呼ばれる。** ゲートウェイ側は単一スレッドで、
// tick() が受信を全部片付けてから送信する直列実行なので、ゲートウェイの内部に排他は無い
// （UDP ソケットは全二重で、送信用と受信用のバッファも別々に持っている）。
//
// **排他が要るのはこの継ぎ目だけ。** RTI のコールバック（reflectAttributeValues など）は
// RTI が持つスレッドで飛んでくるので、実装はキューを1枚挟んでそこに lock を置くこと：
//
//     RTI のスレッド ──→ [ロック付きキュー] ──→ drain() ──→ 周期ループのスレッド
//
// **変換はコールバックの中で済ませること。** RTI のパラメータハンドルや値バッファは
// コールバックの間しか有効でないのが普通で、ポインタを持ち越して後で復号することはできない。
// 復号済みの構造体をキューに積む。
//
// drain() / accept() の中で RTI を呼び返さないこと。RTI 実装によっては
// コールバック中の再入を禁じており、握ったままだと簡単にデッドロックする。
// ─────────────────────────────────────────────────────────────────────

